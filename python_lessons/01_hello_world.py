# Python is a beginner-friendly language.
# Lines starting with '#' are COMMENTS — Python ignores them.
# They exist to explain code to humans.

# --- Your First Python Program ---
print("Hello, World!")

# print() displays output to the screen.
print("My name is Abdurr")
print("I am learning Python!")

# You can print numbers too
print(42)
print(3.14)

# Print multiple things at once using commas
print("I am", 20, "years old")

# --- Empty line ---
print()   # prints a blank line

# --- String with single quotes ---
print('Single quotes work too!')

